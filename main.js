// ─── LIGHTBOX ──────────────────────────────────────────────────────────────
let lbImages = [];
let lbIndex = 0;

const lightbox = document.getElementById('lightbox');
const lbImg = document.getElementById('lbImg');
const lbCounter = document.getElementById('lbCounter');

function openLightbox(images, startIndex) {
  lbImages = images;
  lbIndex = startIndex;
  updateLightbox();
  lightbox.classList.add('open');
  document.body.style.overflow = 'hidden';
}

function closeLightbox() {
  lightbox.classList.remove('open');
  document.body.style.overflow = '';
}

function updateLightbox() {
  lbImg.src = lbImages[lbIndex];
  lbCounter.textContent = lbImages.length > 1 ? `${lbIndex + 1} / ${lbImages.length}` : '';
  document.getElementById('lbPrev').style.display = lbImages.length > 1 ? '' : 'none';
  document.getElementById('lbNext').style.display = lbImages.length > 1 ? '' : 'none';
}

document.getElementById('lbClose').addEventListener('click', closeLightbox);
document.getElementById('lbPrev').addEventListener('click', () => {
  lbIndex = (lbIndex - 1 + lbImages.length) % lbImages.length;
  updateLightbox();
});
document.getElementById('lbNext').addEventListener('click', () => {
  lbIndex = (lbIndex + 1) % lbImages.length;
  updateLightbox();
});
lightbox.addEventListener('click', e => { if (e.target === lightbox) closeLightbox(); });
document.addEventListener('keydown', e => {
  if (!lightbox.classList.contains('open')) return;
  if (e.key === 'Escape') closeLightbox();
  if (e.key === 'ArrowLeft') { lbIndex = (lbIndex - 1 + lbImages.length) % lbImages.length; updateLightbox(); }
  if (e.key === 'ArrowRight') { lbIndex = (lbIndex + 1) % lbImages.length; updateLightbox(); }
});

// ─── RENDER ────────────────────────────────────────────────────────────────
function photosHTML(images, buildingId) {
  if (!images || images.length === 0) return '';
  const count = images.length;
  const items = images.map((src, i) =>
    `<div class="photo-item" data-bid="${buildingId}" data-idx="${i}">
      <img src="${src}" alt="" loading="lazy" onerror="this.classList.add('error')" />
    </div>`
  ).join('');
  return `<div class="building-photos count-${count}">${items}</div>`;
}

function buildingHTML(b, index) {
  const num = String(index + 1).padStart(2, '0');
  const textParagraphs = b.text.split('\n\n').filter(Boolean)
    .map(p => `<p>${p.trim()}</p>`).join('');
  const photos = photosHTML(b.images || [], b.id);

  return `
    <article class="building reveal" id="b-${b.id}">
      <div class="building-accent"></div>
      <div class="building-index">${num}</div>
      <div class="building-body">
        <div class="building-meta">
          <span class="building-address">${b.address}</span>
          ${b.years ? `<span class="building-years">${b.years}</span>` : ''}
        </div>
        <h2 class="building-title">${b.title}</h2>
        ${b.architects ? `<div class="building-architects">Архитекторы: ${b.architects}</div>` : ''}
        <div class="building-text">${textParagraphs}</div>
        ${photos}
      </div>
    </article>`;
}

function renderAll() {
  const container = document.getElementById('buildingsContainer');
  const navItems = document.getElementById('navItems');

  let html = '';
  STATIC_BUILDINGS.forEach((b, i) => {
    if (i > 0) html += `<div class="section-divider"><span>●</span></div>`;
    html += buildingHTML(b, i);
  });
  container.innerHTML = html;

  navItems.innerHTML = STATIC_BUILDINGS.map(b =>
    `<a href="#b-${b.id}">${b.title}</a>`
  ).join('');

  // Attach lightbox clicks
  container.querySelectorAll('.photo-item').forEach(item => {
    item.addEventListener('click', () => {
      const bid = item.dataset.bid;
      const idx = parseInt(item.dataset.idx);
      const building = STATIC_BUILDINGS.find(b => b.id === bid);
      if (building && building.images) openLightbox(building.images, idx);
    });
  });

  // Scroll reveal
  const observer = new IntersectionObserver(entries => {
    entries.forEach(e => {
      if (e.isIntersecting) { e.target.classList.add('visible'); observer.unobserve(e.target); }
    });
  }, { threshold: 0.06 });

  document.querySelectorAll('.reveal').forEach(el => observer.observe(el));
}

// ─── INIT ───────────────────────────────────────────────────────────────────
renderAll();
